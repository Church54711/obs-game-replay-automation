#Requires -Version 5.1
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$sourceRoot = Join-Path $PSScriptRoot 'src'
$version = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'VERSION')).Trim()
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw 'Invalid bundle version.' }
$parts = [IO.File]::ReadAllText((Join-Path $sourceRoot 'bundle.json')) | ConvertFrom-Json
$bundle = "-- Generated by build-lua.ps1. Edit the components in src/, then rebuild.`n"
foreach ($part in $parts) {
    if ($part -notmatch '^\d{2}-[a-z-]+\.lua$') { throw "Invalid source component: $part" }
    $content = [IO.File]::ReadAllText((Join-Path $sourceRoot $part)).Replace("`r`n", "`n").TrimEnd()
    $bundle += "`n-- BEGIN $part`n$content`n-- END $part`n"
}
$output = Join-Path $PSScriptRoot 'game-replay-auto.lua'
$bundle = $bundle.Replace('@PACKAGE_VERSION@', $version)
if ($Check) {
    if ([IO.File]::ReadAllText($output).Replace("`r`n", "`n") -cne $bundle) { throw 'Lua bundle is out of date. Run build-lua.ps1.' }
} else { [IO.File]::WriteAllText($output, $bundle, [Text.UTF8Encoding]::new($false)) }
